from mortis.catalog.fields import BASIC, IMAGES, column, extra, image, people, tags
from mortis.catalog.spec import DataTypeSpec, FieldSpec

TV = DataTypeSpec(
    id="tv",
    name="电视剧",
    structure="series",
    subtitle_field="original_title",
    fields=[
        # 剧
        column("title", "剧名", "text", sortable=True),
        column("original_title", "原名", "text"),
        column("sort_title", "排序名", "text", sortable=True),
        column("overview", "剧情", "longtext"),
        column("release_date", "首播", "date", sortable=True, filterable=True),
        extra("status", "状态", "text"),
        extra("runtime", "时长（分钟）", "number"),
        extra("certification", "分级", "text"),
        extra("top250", "排名", "number"),
        FieldSpec(
            field_key="ratings",
            label="评分",
            value_type="rating",
            stored_in="ratings",
            detail_section=BASIC,
            is_sortable=True,
        ),
        tags("genres", "类型", "genre"),
        tags("countries", "国家/地区", "country"),
        tags("studios", "制片公司", "studio"),
        tags("keywords", "标签", "keyword"),
        extra("trailer", "预告片", "url"),
        people("actors", "演员", "actor", filterable=True),
        column("poster", "海报", "images", column="poster_path", section=IMAGES),
        image("fanart", "同人画"),
        image("banner", "横幅"),
        image("clearlogo", "透明标志"),
        image("clearart", "透明艺术图"),
        image("keyart", "关键艺术图"),
        image("thumb", "缩略图"),
        image("characterart", "角色图"),
        # 季
        column("title", "季名", "text", applies_to="season"),
        column("overview", "季简介", "longtext", applies_to="season"),
        column("release_date", "首播", "date", applies_to="season"),
        column(
            "poster",
            "季海报",
            "images",
            column="poster_path",
            applies_to="season",
            section=IMAGES,
        ),
        image("fanart", "季同人画", applies_to="season"),
        image("banner", "季横幅", applies_to="season"),
        image("thumb", "季缩略图", applies_to="season"),
        # 集
        column("title", "标题", "text", applies_to="episode"),
        column("original_title", "原名", "text", applies_to="episode"),
        column("overview", "剧情", "longtext", applies_to="episode"),
        column("release_date", "播出日期", "date", applies_to="episode"),
        FieldSpec(
            field_key="ratings",
            label="评分",
            value_type="rating",
            stored_in="ratings",
            applies_to="episode",
            detail_section=BASIC,
        ),
        people("actors", "演员", "actor", applies_to="episode"),
        people("directors", "导演", "director", applies_to="episode"),
        people("writers", "编剧", "writer", applies_to="episode"),
        people("producers", "制片", "producer", applies_to="episode"),
        image("thumb", "缩略图", applies_to="episode"),
    ],
)
