from mortis.catalog.fields import BASIC, IMAGES, column, extra, image, people, tags
from mortis.catalog.spec import DataTypeSpec, FieldSpec

MOVIE = DataTypeSpec(
    id="movie",
    name="电影",
    structure="item_group",
    subtitle_field="original_title",
    fields=[
        # 系列电影
        column("title", "系列名", "text", applies_to="collection", sortable=True),
        column("original_title", "原名", "text", applies_to="collection"),
        column("overview", "简介", "longtext", applies_to="collection"),
        column(
            "poster",
            "海报",
            "images",
            column="poster_path",
            applies_to="collection",
            section=IMAGES,
        ),
        image("fanart", "同人画", applies_to="collection"),
        image("banner", "横幅", applies_to="collection"),
        image("clearlogo", "透明标志", applies_to="collection"),
        image("discart", "光盘", applies_to="collection"),
        image("thumb", "缩略图", applies_to="collection"),
        # 电影
        column("title", "片名", "text", sortable=True),
        column("original_title", "原名", "text"),
        column("sort_title", "排序名", "text", sortable=True),
        extra("tagline", "标语", "text"),
        column("overview", "剧情", "longtext"),
        column("release_date", "上映日期", "date", sortable=True, filterable=True),
        extra("runtime", "时长（分钟）", "number"),
        extra("certification", "分级", "text"),
        extra("top250", "排名", "number"),
        FieldSpec(
            field_key="ratings",
            label="评分",
            value_type="rating",
            stored_in="ratings",
            detail_section=BASIC,
            is_sortable=True,
        ),
        tags("genres", "类型", "genre"),
        tags("countries", "国家/地区", "country"),
        tags("studios", "制片公司", "studio"),
        tags("keywords", "标签", "keyword"),
        tags("spoken_languages", "对白语言", "language"),
        extra("trailer", "预告片", "url"),
        people("directors", "导演", "director", filterable=True),
        people("writers", "编剧", "writer"),
        people("producers", "制片", "producer"),
        people("actors", "演员", "actor", filterable=True),
        column("poster", "海报", "images", column="poster_path", section=IMAGES),
        image("fanart", "同人画"),
        image("banner", "横幅"),
        image("clearlogo", "透明标志"),
        image("clearart", "透明艺术图"),
        image("discart", "光盘"),
        image("keyart", "关键艺术图"),
        image("thumb", "缩略图"),
        image("extrafanart", "额外同人画"),
    ],
)
